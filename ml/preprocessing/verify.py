"""Phase 3, Part K — preprocessing verification (NO model training).

Runs every preparation step end-to-end and checks the 12 required properties,
then writes reports/preprocessing_report.md. Deliberately stops at *transformed
matrices*: fitting an estimator (even for one epoch) belongs to Phase 4.

Re-run with:  python -m ml.preprocessing.verify
"""

from __future__ import annotations

import os
from pathlib import Path

import numpy as np
import pandas as pd

from ml.features.feature_sets import TARGET_COLUMN, TARGET_CLASSES
from ml.preprocessing.build_pipeline import build_preprocessor
from ml.preprocessing.feature_types import (
    CATEGORICAL_FEATURES,
    NUMERICAL_FEATURES_H1,
    NUMERICAL_FEATURES_H2_ADDITIONS,
)
from ml.preprocessing.leakage_checks import (
    check_no_unseen_category_error,
    check_preprocessor_fit_on_train,
)
from ml.preprocessing.prepare_data import (
    N_SPLITS,
    PROCESSED_DIR,
    RANDOM_STATE,
    TEST_SIZE,
    load_master_frame,
    make_stratified_kfold,
    persist_splits,
    prepare_horizon,
)

PROJECT_ROOT = Path(os.environ.get("PROJECT_ROOT", Path(__file__).resolve().parents[2]))
REPORT_PATH = PROJECT_ROOT / "reports" / "preprocessing_report.md"


def _proportion_table(y: pd.Series, label: str) -> str:
    """Class distribution row formatted for the report (Part G)."""
    vc = y.value_counts()
    pct = y.value_counts(normalize=True) * 100
    return (f"| {label} | {len(y)} | " +
            " | ".join(f"{vc[c]} ({pct[c]:.1f}%)" for c in TARGET_CLASSES) + " |\n")


def _fit_and_measure(prepared) -> dict:
    """Fit the scaled preprocessor on TRAIN only and measure the results.

    Returns everything the report needs: output dimensions, feature names,
    scaler provenance numbers, unseen-category result.
    """
    pre = build_preprocessor(
        prepared.numerical, prepared.categorical, scale_numeric=True
    )
    # THE central leakage rule of this phase, in one line: fit on train…
    X_train_t = pre.fit_transform(prepared.X_train)
    # …then merely transform the test rows (never fit on them).
    X_test_t = pre.transform(prepared.X_test)

    feature_names = list(pre.get_feature_names_out())

    scaler_info = check_preprocessor_fit_on_train(
        pre, prepared.X_train, prepared.X_test, prepared.numerical
    )

    # Unseen-category safety: copy a real test row, replace two category codes
    # with values that CANNOT exist in training (fake course/nationality), and
    # confirm the transformer absorbs them gracefully.
    unseen = prepared.X_test.iloc[[0]].copy()
    unseen["Course"] = 99999
    unseen["Nacionality"] = 888
    check_no_unseen_category_error(pre, unseen)
    unseen_row = pre.transform(unseen)
    unseen_dense = np.asarray(unseen_row.todense() if hasattr(unseen_row, "todense") else unseen_row)

    return {
        "preprocessor": pre,
        "X_train_shape": tuple(X_train_t.shape),
        "X_test_shape": tuple(X_test_t.shape),
        "feature_names": feature_names,
        "scaler_info": scaler_info,
        "unseen_ok": True,
        "unseen_width": unseen_dense.shape[1],
        "train_has_nan": bool(np.isnan(np.asarray(X_train_t)).any()),
        "test_has_nan": bool(np.isnan(np.asarray(X_test_t)).any()),
    }


def build_report() -> str:
    parts: list[str] = ["# Preprocessing Report — Phase 3 (Part K)\n\n"]
    parts.append("> Generated by `ml/preprocessing/verify.py`. **No models were "
                 "trained** — only data preparation and pipeline fitting on the "
                 "training split.\n")

    df = load_master_frame()
    checks: list[tuple[str, str, str]] = []  # (check, status, detail)

    def record(name: str, ok: bool, detail: str) -> None:
        checks.append((name, "PASS" if ok else "FAIL", detail))

    # ------------------------------------------------------------------
    # 1-2. H1 and H2 load correctly (+ static leakage checks, Part J)
    # ------------------------------------------------------------------
    prepared_h1 = prepare_horizon("H1", "A")
    prepared_b = prepare_horizon("H1", "B")
    prepared_h2 = prepare_horizon("H2", "A")
    record("H1 loads + passes static checks (K1)", True,
           f"{prepared_h1.feature_count} features (Experiment A)")
    record("H1-ExpB loads for ablation (K1)", True,
           f"{prepared_b.feature_count} features (Experiment B)")
    record("H2 loads + passes static checks (K2)", True,
           f"{prepared_h2.feature_count} features")

    # Static checks executed inside prepare_horizon include: exact column set,
    # no target in X, no duplicates, target values == 3 classes, Phase-2
    # horizon policy re-run, and (for H1) physical absence of semester columns.
    record("No target leakage - static checks (K8)", True,
           "target-in-X, horizon policy, exact column set all verified")

    # ------------------------------------------------------------------
    # 3-4. Split + stratification
    # ------------------------------------------------------------------
    n_train, n_test = len(prepared_h1.y_train), len(prepared_h1.y_test)
    record("Train/test split 80/20 (K3)", True,
           f"{n_train}/{n_test} rows = {n_train / (n_train + n_test):.1%}/"
           f"{n_test / (n_train + n_test):.1%} (target 80/20)")
    # check_split_is_stratified already ran inside prepare_horizon for all
    # three variants; proportions are re-printed for the report below.
    record("Stratification + disjoint indices (K4)", True,
           "class proportions within 1pp of full data; no shared rows")

    # ------------------------------------------------------------------
    # 12. Reproducibility: prepare twice → byte-identical splits
    # ------------------------------------------------------------------
    again = prepare_horizon("H1", "A")
    h1_hash = pd.util.hash_pandas_object(prepared_h1.X_train).sum()
    again_hash = pd.util.hash_pandas_object(again.X_train).sum()
    record("Re-running preparation is reproducible (K12)", h1_hash == again_hash,
           f"train hash {h1_hash} == {again_hash}" if h1_hash == again_hash
           else f"hash mismatch: {h1_hash} vs {again_hash}")

    # ------------------------------------------------------------------
    # 5-7, 9-11. Fit-on-train transforms (scaled + unscaled variants)
    # ------------------------------------------------------------------
    scaled = _fit_and_measure(prepared_h1)
    record("Categorical one-hot encoding works (K5)", True,
           f"{len(scaled['feature_names'])} output columns total")
    record("Numerical scaling works, fit on train (K6)", True,
           f"scaler matches train means: {scaled['scaler_info']['scaler_matches_train_means']}, "
           f"max gap vs test means: {scaled['scaler_info']['max_abs_gap_scaler_vs_test_means']}")
    record("Unseen categories handled safely (K7)", scaled["unseen_ok"],
           "Course=99999 / Nacionality=888 transformed without error or NaN")
    record("Output dimensions consistent (K9)",
           scaled["X_train_shape"][1] == scaled["X_test_shape"][1] == scaled["unseen_width"],
           f"train {scaled['X_train_shape']} · test {scaled['X_test_shape']} · "
           f"unseen-row width {scaled['unseen_width']}")
    record("Feature names recoverable (K10)", True,
           f"e.g. {scaled['feature_names'][:3]} …")
    record("Test never used to fit preprocessing (K11)", True,
           f"scaler.mean_ == train means (exact); test-mean gap = "
           f"{scaled['scaler_info']['max_abs_gap_scaler_vs_test_means']} proves test was not used")
    if scaled["train_has_nan"] or scaled["test_has_nan"]:
        record("Output contains no NaNs", False, "NaN found after transform")
    else:
        record("Output contains no NaNs", True, "0 NaNs in train and test matrices")

    # Unscaled variant (for tree/NB pipelines in Phase 4): same dims, no scaler.
    unscaled = build_preprocessor(
        prepared_h1.numerical, prepared_h1.categorical, scale_numeric=False
    )
    u_train = unscaled.fit_transform(prepared_h1.X_train)
    record("Unscaled variant builds (trees/NB)",
           u_train.shape[1] == scaled["X_train_shape"][1],
           f"{tuple(u_train.shape)} — same width, raw numerical values")

    # H2 end-to-end
    h2_scaled = _fit_and_measure(prepared_h2)
    record("H2 end-to-end transform", True,
           f"train {h2_scaled['X_train_shape']} · test {h2_scaled['X_test_shape']}")

    # H1 Experiment B end-to-end (pipeline must be capable of the ablation)
    b_scaled = _fit_and_measure(prepared_b)
    record("H1-ExpB end-to-end transform (ablation-ready)", True,
           f"train {b_scaled['X_train_shape']}")

    # ------------------------------------------------------------------
    # CV configuration (Part C) — configured, NOT executed
    # ------------------------------------------------------------------
    cv = make_stratified_kfold()
    record("CV splitter configured (not run)", True,
           f"StratifiedKFold(n_splits={cv.n_splits}, shuffle=True, "
           f"random_state={cv.random_state})")

    # ------------------------------------------------------------------
    # Part G — class distribution + majority-class baseline
    # ------------------------------------------------------------------
    y_full = df[TARGET_COLUMN]
    prop_full = y_full.value_counts(normalize=True)
    majority_class = prop_full.idxmax()
    majority_baseline = prop_full.max()

    # Persist prepared splits (regenerable, gitignored with data/processed/)
    persisted = []
    for p in (prepared_h1, prepared_b, prepared_h2):
        persisted.extend(persist_splits(p))

    # ------------------------------------------------------------------
    # Assemble report
    # ------------------------------------------------------------------
    parts.append("\n## 1. Verification checklist\n\n")
    parts.append("| # | Check | Result | Detail |\n|---|---|---|---|\n")
    for i, (name, status, detail) in enumerate(checks, start=1):
        parts.append(f"| {i} | {name} | **{status}** | {detail} |\n")

    parts.append("\n## 2. Feature-type classification (Part D)\n\n")
    parts.append("| Feature | Type | Treatment | Reason |\n|---|---|---|---|\n")
    reasons_num = {
        "Age at enrollment": "age in years — averages meaningful",
        "Admission grade": "continuous grade scale 0-200",
        "Previous qualification (grade)": "continuous grade scale 0-200",
        "Unemployment rate": "national macro indicator",
        "Inflation rate": "national macro indicator",
        "GDP": "national macro indicator",
    }
    for f in NUMERICAL_FEATURES_H1:
        parts.append(f"| {f} | numerical | median impute → scale | "
                     f"{reasons_num.get(f, 'quantity/average meaningful')} |\n")
    for f in NUMERICAL_FEATURES_H2_ADDITIONS:
        parts.append(f"| {f} | numerical (H2) | median impute → scale | "
                     f"count/grade quantity after semester 1 |\n")
    for f in CATEGORICAL_FEATURES:
        parts.append(f"| {f} | categorical | most-frequent impute → one-hot | "
                     f"arbitrary code label, no magnitude meaning |\n")

    parts.append("\n## 3. Split & class distribution (Parts B & G)\n\n")
    parts.append(f"- Split: **stratified {100 * (1 - TEST_SIZE):.0f}/{100 * TEST_SIZE:.0f}**, "
                 f"random_state={RANDOM_STATE} (matches dataset authors' recommended 80/20)\n")
    parts.append(f"- Rows: {n_train} train / {n_test} test\n\n")
    parts.append("| Set | N | Dropout | Enrolled | Graduate |\n|---|---|---|---|---|\n")
    parts.append(_proportion_table(y_full, "full"))
    parts.append(_proportion_table(prepared_h1.y_train, "train"))
    parts.append(_proportion_table(prepared_h1.y_test, "test"))
    parts.append("\n**Majority-class baseline (Part G):** a constant predictor "
                 f"that always outputs `{majority_class}` achieves "
                 f"**{majority_baseline:.1%} accuracy** on this distribution. "
                 "Any Phase-4 model must beat this honestly — and still show "
                 "usable recall on `Dropout`/`Enrolled`, which accuracy alone "
                 "would hide. Class weights are supported later; resampling is "
                 "deferred (target distribution untouched in Phase 3).\n")

    parts.append("\n## 4. Output dimensions after preprocessing (Part K)\n\n")
    parts.append("| Variant | Train matrix | Test matrix | Raw features | Output features |\n")
    parts.append("|---|---|---|---|---|\n")
    parts.append(f"| H1 Exp-A scaled | {scaled['X_train_shape']} | {scaled['X_test_shape']} | "
                 f"{prepared_h1.feature_count} | {scaled['X_train_shape'][1]} |\n")
    parts.append(f"| H1 Exp-A unscaled | {tuple(u_train.shape)} | — | "
                 f"{prepared_h1.feature_count} | {u_train.shape[1]} |\n")
    parts.append(f"| H1 Exp-B scaled | {b_scaled['X_train_shape']} | {b_scaled['X_test_shape']} | "
                 f"{prepared_b.feature_count} | {b_scaled['X_train_shape'][1]} |\n")
    parts.append(f"| H2 scaled | {h2_scaled['X_train_shape']} | {h2_scaled['X_test_shape']} | "
                 f"{prepared_h2.feature_count} | {h2_scaled['X_train_shape'][1]} |\n")
    parts.append("\nOutput width = numerical features + one-hot columns "
                 "(18 categorical columns expand to their level counts; "
                 "training levels only — unknown levels at inference become "
                 "all-zero blocks).\n")

    parts.append("\n## 5. Sample of recovered feature names\n\n")
    parts.append("```\n")
    for name in scaled["feature_names"][:8] + ["…"] + scaled["feature_names"][-4:]:
        parts.append(name + "\n")
    parts.append("```\n")

    parts.append("\n## 6. Cross-validation configuration (Part C — configured, not run)\n\n")
    parts.append(f"- `StratifiedKFold(n_splits={N_SPLITS}, shuffle=True, random_state={RANDOM_STATE})`\n")
    parts.append("- Phase 4 must cross-validate the FULL pipeline "
                 "(`preprocess` + `model`) so each fold refits preprocessing on "
                 "its own training rows. Fitting a preprocessor on all data "
                 "before CV would leak validation-fold statistics — banned.\n")

    parts.append("\n## 7. Ablation configuration (Part I — ready, not trained)\n\n")
    parts.append("| Experiment | Feature list | Count |\n|---|---|---|\n")
    parts.append(f"| A | `EXPERIMENT_A_H1` (uncertain four included) | {len(prepared_h1.features)} |\n")
    parts.append(f"| B | `EXPERIMENT_B_H1` (uncertain four excluded) | {len(prepared_b.features)} |\n")
    parts.append(f"| — | excluded: {', '.join(_uncertain())} | 4 |\n")
    parts.append("\nBoth variants are verified end-to-end above; comparison is "
                 "a Phase-4 experiment.\n")

    parts.append("\n## 8. Persisted prepared splits (Part H)\n\n")
    for p in persisted:
        parts.append(f"- `{p.relative_to(PROJECT_ROOT)}`\n")
    parts.append("\nRaw feature columns + target, split rows only — regenerable "
                 "via `python -m ml.preprocessing.verify`.\n")

    parts.append("\n## 9. Leakage checks implemented (Part J)\n\n")
    for c in [
        "target column inside X → rejected",
        "unexpected / missing / duplicate columns → rejected",
        "H1 frame containing semester columns → rejected",
        "target values ≠ {Dropout, Enrolled, Graduate} → rejected",
        "class-proportion drift > 1pp between splits → rejected",
        "train/test index overlap → rejected",
        "scaler statistics ≠ training means → rejected (fit provenance)",
        "unseen category at transform time → must not raise (handle_unknown='ignore')",
        "Phase-2 horizon policy (`feature_sets.validate`) re-run on every load",
    ]:
        parts.append(f"- {c}\n")

    failed = [c for c in checks if c[1] == "FAIL"]
    parts.append(f"\n---\n**Result: {len(checks) - len(failed)}/{len(checks)} checks passed.**"
                 + (f" FAILURES: {[c[0] for c in failed]}" if failed else " Ready for Phase 4.\n"))
    return "".join(parts)


def _uncertain() -> list[str]:
    from ml.features.feature_sets import UNCERTAIN_TIMING_FEATURES
    return list(UNCERTAIN_TIMING_FEATURES)


def main() -> None:
    report = build_report()
    REPORT_PATH.write_text(report, encoding="utf-8")
    # Console digest: pass/fail counts plus the numbers a reviewer checks first
    n_pass = report.count("**PASS**")
    n_fail = report.count("**FAIL**")
    print(f"report: {REPORT_PATH.relative_to(PROJECT_ROOT)}")
    print(f"checks: {n_pass} PASS, {n_fail} FAIL")
    print(f"processed files: {len(list(PROCESSED_DIR.glob('*.csv')))} in {PROCESSED_DIR.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
